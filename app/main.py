import json
from pathlib import Path

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, PlainTextResponse

from app.engine import (
    compute_fingerprint,
    compute_sre_metrics,
    export_full_suite,
    synthesize_test,
)
from app.models import (
    IncidentStatus,
    ProductionIncident,
    SREMetrics,
    SynthesizedTestCase,
)

app = FastAPI(
    title="EvalSRE",
    description="Incident-to-regression case engineering pipeline turning chatbot failures into reproducible test suites.",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

WEB_DIR = Path(__file__).parent / "web"
INCIDENTS_PATH = Path(__file__).parents[1] / "benchmarks" / "production_incidents.json"


def _load_incidents() -> list[ProductionIncident]:
    if not INCIDENTS_PATH.exists():
        return []
    data = json.loads(INCIDENTS_PATH.read_text(encoding="utf-8"))
    incidents = []
    for item in data.get("incidents", []):
        if not item.get("sha256_fingerprint"):
            item["sha256_fingerprint"] = compute_fingerprint(
                item["prompt"], item["category"], item["failing_response"]
            )
        incidents.append(ProductionIncident(**item))
    return incidents


@app.get("/health", include_in_schema=False)
def health():
    return {"status": "ok", "service": "evalsre"}


@app.get("/api/incidents")
def get_incidents():
    return [i.model_dump() for i in _load_incidents()]


@app.post("/api/incidents/create", response_model=ProductionIncident)
def create_incident(incident: ProductionIncident):
    if not incident.sha256_fingerprint:
        incident.sha256_fingerprint = compute_fingerprint(
            incident.prompt, incident.category.value, incident.failing_response
        )
    return incident


@app.post("/api/synthesize", response_model=SynthesizedTestCase)
def synthesize(incident: ProductionIncident):
    incident.status = IncidentStatus.TEST_SYNTHESIZED
    return synthesize_test(incident)


@app.get("/api/export/pytest")
def export_pytest():
    incidents = _load_incidents()
    code = export_full_suite(incidents)
    return PlainTextResponse(code, media_type="text/x-python")


@app.get("/api/metrics", response_model=SREMetrics)
def get_metrics():
    incidents = _load_incidents()
    return compute_sre_metrics(incidents)


@app.post("/api/reports/markdown")
def generate_markdown(incidents: list[ProductionIncident]):
    metrics = compute_sre_metrics(incidents)

    rows = []
    for i in incidents:
        rows.append(
            f"| `{i.incident_id}` | `{i.severity.value}` | `{i.category.value}` | `{i.status.value}` | `{i.sha256_fingerprint[:8]}...` | {i.title} |"
        )
    rows_text = (
        "\n".join(rows) if rows else "| None | - | - | - | - | No incidents recorded |"
    )

    md = f"""# EvalSRE - AI Site Reliability & Regression Engineering Audit

**Total Production Incidents:** {metrics.total_incidents}  
**Open SEV-1 Critical Blockers:** `{metrics.open_sev1_count}`  
**Resolution Rate:** `{round(metrics.resolution_rate * 100, 1)}%` ({metrics.resolved_count}/{metrics.total_incidents} Resolved)  
**Automated Pytest Tests Synthesized:** `{metrics.tests_synthesized_count}`  

---

## 1. Incident Breakdown by Failure Category
{chr(10).join([f"- **{cat}:** `{count}`" for cat, count in metrics.category_breakdown.items()])}

---

## 2. Production Incident Ledger & Fingerprints
| Incident ID | Severity | Category | Status | SHA-256 | Description |
|---|---|---|---|---|---|
{rows_text}

_Generated by EvalSRE Regression Engineering Pipeline v0.1.0_
"""
    return PlainTextResponse(md, media_type="text/markdown")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(WEB_DIR / "index.html")


@app.get("/app.js", include_in_schema=False)
def javascript():
    return FileResponse(WEB_DIR / "app.js", media_type="text/javascript")


@app.get("/style.css", include_in_schema=False)
def stylesheet():
    return FileResponse(WEB_DIR / "style.css", media_type="text/css")
