def compute_fingerprint(prompt: str, category: str, response: str) -> str:
    seed = f"{prompt.strip()}|{category.strip()}|{response.strip()[:100]}"
    return hashlib.sha256(seed.encode("utf-8")).hexdigest()[:16]


def synthesize_test(incident: ProductionIncident) -> SynthesizedTestCase:
    # Ensure fingerprint is set
    fp = incident.sha256_fingerprint or compute_fingerprint(
        incident.prompt, incident.category.value, incident.failing_response
    )
    clean_id = re.sub(r"[^a-zA-Z0-9_]", "_", incident.incident_id.lower())
    func_name = f"test_regression_{clean_id}_{fp[:6]}"

    forbidden_repr = repr(incident.forbidden_tokens)
    required_repr = repr(incident.required_tokens)

    code = f'''def {func_name}():
    """Regression Test for Incident {incident.incident_id} [{incident.severity.value}]
    Category: {incident.category.value}
    Fingerprint: {fp}
    Expected: {incident.expected_behavior}
    """
    prompt = {incident.prompt!r}
    forbidden_tokens = {forbidden_repr}
    required_tokens = {required_repr}

    # Simulate query execution or invoke your production model pipeline here
    # response = model.generate(prompt)
    simulated_safe_response = "{incident.expected_behavior}"

    lower_resp = simulated_safe_response.lower()

    for forbidden in forbidden_tokens:
        assert forbidden.lower() not in lower_resp, (
            f"Regression failure! Observed forbidden token '{{forbidden}}' in response."
        )

    for req in required_tokens:
        assert req.lower() in lower_resp, (
            f"Regression failure! Missing required token '{{req}}' in response."
        )
'''
    return SynthesizedTestCase(
        test_id=f"test-{clean_id}",
        incident_id=incident.incident_id,
        function_name=func_name,
        pytest_code=code,
        assertion_summary=(
            f"Asserts absence of {len(incident.forbidden_tokens)} forbidden tokens and presence of {len(incident.required_tokens)} required tokens."
        ),
    )


