def compute_sre_metrics(incidents: list[ProductionIncident]) -> SREMetrics:
    total = len(incidents)
    resolved = sum(1 for i in incidents if i.status == IncidentStatus.VERIFIED_RESOLVED)
    open_sev1 = sum(
        1
        for i in incidents
        if i.severity == IncidentSeverity.SEV1_CRITICAL and i.status != IncidentStatus.VERIFIED_RESOLVED
    )
    synthesized = sum(1 for i in incidents if i.status in [IncidentStatus.TEST_SYNTHESIZED, IncidentStatus.PATCHED, IncidentStatus.VERIFIED_RESOLVED])

    cats: dict[str, int] = {}
    for i in incidents:
        val = i.category.value
        cats[val] = cats.get(val, 0) + 1

    rate = round(resolved / total, 4) if total > 0 else 1.0

    return SREMetrics(
        total_incidents=total,
        resolved_count=resolved,
        open_sev1_count=open_sev1,
        tests_synthesized_count=synthesized,
        resolution_rate=rate,
        category_breakdown=cats,
    )
